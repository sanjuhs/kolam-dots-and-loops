// Run against a local server with Playwright available; the resulting data is shared by browser and API.
const fs = require("node:fs");
const { chromium } = require("playwright");
require("../motifs.js");
const engine = require("../puzzle-engine.js");
(async () => {
  const cases = new Map();
  function add(art, n) {
    const key = engine.pictureHash(art, n);
    cases.set(key, { key, art, n });
  }
  for (let L = 5; L <= 100000; L += 10) {
    const mi = ((L - 5) / 10) % MOTIFS.length,
      n = engine.picSize(L),
      rng = engine.mulberry32(L * 2654435761 + n);
    add(MOTIFS[mi].draw(rng), n);
  }
  for (let mi = 0; mi < MOTIFS.length; mi++)
    for (const n of [2, 3, 4, 5, 6, 8, 10, 12])
      add(MOTIFS[mi].draw(engine.mulberry32((1000 + mi) * 2654435761 + n)), n);
  const browser = await chromium.launch({
    executablePath:
      process.env.CHROME_PATH ||
      "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    headless: true,
  });
  try {
    const page = await browser.newPage();
    await page.goto(process.env.BASE_URL || "http://127.0.0.1:8772");
    const result = {};
    for (const { key, art, n } of cases.values())
      result[key] = await page.evaluate(
        async ({ art, n }) => tileSyms(art, n),
        { art, n },
      );
    fs.writeFileSync(
      new URL("../picture-symmetries.js", `file://${__filename}`),
      "'use strict';\n// Canonical rotation equivalence for ranked pictures; generated by scripts/build-picture-symmetries.cjs.\nglobalThis.PictureSyms=" +
        JSON.stringify(result) +
        ";\n",
    );
    console.log(
      "Generated canonical symmetries for",
      cases.size,
      "art/size variants, covering 100,000 numbered levels and all gallery sizes.",
    );
  } finally {
    await browser.close();
  }
})().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
